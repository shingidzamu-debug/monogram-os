// Splits the single-file app (index.html) into the pieces the Next.js shell
// serves. index.html stays the source of truth; the outputs are generated on
// every `npm run dev` / `npm run build` and are not committed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');

const pick = (re, what) => {
  const m = html.match(re);
  if (!m) throw new Error(`build-legacy: could not find ${what} in index.html`);
  return m[1];
};

const head = pick(/<head>([\s\S]*?)<\/head>/i, '<head>');
const title = pick(/<title>([\s\S]*?)<\/title>/i, '<title>').trim();
const links = [...head.matchAll(/<link\s+([^>]*?)\/?>/gi)].map(([, attrs]) =>
  Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))
);
const styles = [...head.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)].map(m => m[1]).join('\n');
const body = pick(/<body[^>]*>([\s\S]*)<\/body>/i, '<body>');
const scripts = [...body.matchAll(/<script>([\s\S]*?)<\/script>/gi)].map(m => m[1]);
if (!scripts.length) throw new Error('build-legacy: no inline <script> in <body>');
const markup = body.replace(/<script>[\s\S]*?<\/script>/gi, '').trim();

writeFileSync(
  join(root, 'app', 'legacy.generated.js'),
  '// Generated by scripts/build-legacy.mjs from index.html. Do not edit.\n' +
    `export const title = ${JSON.stringify(title)};\n` +
    `export const links = ${JSON.stringify(links)};\n` +
    `export const css = ${JSON.stringify(styles)};\n` +
    `export const markup = ${JSON.stringify(markup)};\n`
);
mkdirSync(join(root, 'public', 'legacy'), { recursive: true });
writeFileSync(join(root, 'public', 'legacy', 'app.js'), scripts.join('\n;\n'));
console.log(`build-legacy: ${title} — ${(markup.length / 1024).toFixed(0)} KB markup, ${(styles.length / 1024).toFixed(0)} KB css`);
